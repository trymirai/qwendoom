"""Generate native/trace/qd_tokens.h (token ids, families, fault causes) from the installed
chipformer.rv.spec, so the C trace code can never drift from the vocabulary.

    uv run python native/trace/gen_tokens.py            # rewrite qd_tokens.h
    uv run python native/trace/gen_tokens.py --check    # exit 1 if qd_tokens.h is stale

The record rules themselves are not generated: qd_ref.c ports them by hand (Qwenputer
chipformer/rv/ref.py, MIT (c) 2026 Divyansh Agrawal) and the tests compare token for token.
"""

import argparse
import sys
from pathlib import Path

from chipformer.rv import spec as S

OUT = Path(__file__).with_name("qd_tokens.h")


def ident(name: str) -> str:
    return "".join(c if c.isalnum() else "_" for c in name).upper()


def render() -> str:
    fams = [n for n, _ in S.FAMILY_SIZES] + list(S.CONTROL_NAMES)
    final_mask = sum(1 << i for i, n in enumerate(fams) if n in S.FINAL)
    L = ["/* Generated by native/trace/gen_tokens.py from chipformer.rv.spec (Qwenputer,",
         "   MIT (c) 2026 Divyansh Agrawal). Do not edit: rerun the script. */",
         "#ifndef QD_TOKENS_H", "#define QD_TOKENS_H", "", "#include <stdint.h>", "",
         "/* token families: QD_TOK_<F> is the id of payload 0, QD_TOK_<F>_SIZE the payloads */"]
    for n, s in S.FAMILY_SIZES:
        base, size = S.FAMILIES[n]
        L.append(f"#define QD_TOK_{ident(n)} {base}")
        L.append(f"#define QD_TOK_{ident(n)}_SIZE {size}")
    L += ["", "/* controls (no payload) */", f"#define QD_TOK_CTRL {S.CTRL}"]
    L += [f"#define QD_TOK_{ident(n)} {S.CONTROLS[n]}" for n in S.CONTROL_NAMES]
    L += ["", f"#define QD_VOCAB {S.VOCAB}",
          "#define QD_TOK_PAD QD_VOCAB /* the model's PAD row */",
          "", "/* family ids (QD_FAM_*), in vocabulary order; controls after the families */"]
    L += [f"#define QD_FAM_{ident(n)} {i}" for i, n in enumerate(fams)]
    L += [f"#define QD_N_FAMS {len(fams)}",
          f"#define QD_FAM_FINAL_MASK 0x{final_mask:x}u /* 1 << fam for the record-final ones */",
          "", "static const char *const qd_fam_names[QD_N_FAMS] = {",
          "    " + ", ".join(f'"{n}"' for n in fams) + "};", "",
          "/* the family of a token (QD_FAM_*) and its payload; -1 if t is not a chip token */",
          "static inline int qd_tok_family(int32_t t, uint32_t *payload) {",
          "    if (t < 0 || t >= QD_VOCAB) return -1;",
          "    if (t >= QD_TOK_CTRL) { *payload = 0; "
          f"return {len(S.FAMILY_SIZES)} + (t - QD_TOK_CTRL); }}"]
    for i, (n, _) in enumerate(S.FAMILY_SIZES):
        nxt = (f"QD_TOK_{ident(S.FAMILY_SIZES[i + 1][0])}" if i + 1 < len(S.FAMILY_SIZES)
               else "QD_TOK_CTRL")
        L.append(f"    if (t < {nxt}) {{ *payload = (uint32_t)(t - QD_TOK_{ident(n)}); "
                 f"return QD_FAM_{ident(n)}; }}")
    L += ["    return -1;", "}", "", "/* fault causes (the FLT payload) */"]
    L += [f"#define QD_FAULT_{ident(n)} {i}" for i, n in enumerate(S.FAULTS)]
    L += [f"#define QD_N_FAULTS {len(S.FAULTS)}", "static const char *const qd_fault_names[] = {",
          "    " + ", ".join(f'"{n}"' for n in S.FAULTS) + "};", "",
          "/* record constants */",
          f"#define QD_N_MAX {S.N_MAX} "
          "/* an R refresh comes before the instruction when n == N_MAX */",
          f"#define QD_MISA 0x{S.MISA:08x}u", "",
          "/* upstream chipformer's address map (for validating against upstream ELFs) */",
          f"#define QD_UP_RAM_BASE 0x{S.RAM_BASE:x}u",
          f"#define QD_UP_RAM_SIZE 0x{4 * S.RAM_WORDS:x}u",
          f"#define QD_UP_DROM_BASE 0x{S.DROM_BASE:x}u",
          f"#define QD_UP_DROM_SIZE 0x{4 * S.DROM_WORDS:x}u",
          f"#define QD_UP_ROM_BASE 0x{S.ROM_BASE:x}u",
          f"#define QD_UP_ROM_SIZE 0x{4 * S.ROM_WORDS:x}u",
          f"#define QD_UP_SP_INIT 0x{S.SP_INIT:x}u", "", "#endif", ""]
    return "\n".join(L)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if the header is stale")
    args = ap.parse_args()
    text = render()
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT} is stale: rerun {Path(__file__).name}", file=sys.stderr)
            sys.exit(1)
        return
    OUT.write_text(text)


if __name__ == "__main__":
    main()
